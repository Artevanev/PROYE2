import os
import joblib
import pandas as pd
import streamlit as st

st.set_page_config(page_title="Clasificación de exceso de peso", page_icon="🩺", layout="centered")

RUTA_MODELO = "modelo_exceso.joblib"
RUTA_RANGOS = "rangos.joblib"
DEFAULTS = {"edad": 14, "sexo": "FEMENINO", "actividad": "NO", "habitos": "NO"}


@st.cache_resource
def cargar_recursos():
    if not os.path.exists(RUTA_MODELO) or not os.path.exists(RUTA_RANGOS):
        return None, None
    return joblib.load(RUTA_MODELO), joblib.load(RUTA_RANGOS)


def resetear():
    for k, v in DEFAULTS.items():
        st.session_state[k] = v


for k, v in DEFAULTS.items():
    st.session_state.setdefault(k, v)

modelo, rangos = cargar_recursos()
st.title("CLASIFICACIÓN: ¿EXCESO DE PESO?")
st.caption("Autor: Maria Vanessa Arteaga Villena")

if modelo is None:
    st.error("No se encontraron 'modelo_exceso.joblib' y 'rangos.joblib'. Ejecuta primero el notebook.")
    st.stop()

with st.sidebar:
    st.header("Datos del estudiante")
    st.number_input("Edad (años)", min_value=rangos["EDAD_min"], max_value=rangos["EDAD_max"],
                    step=1, key="edad")
    st.selectbox("Sexo", ["FEMENINO", "MASCULINO"], key="sexo")
    st.selectbox("¿Actividad física baja?", ["NO", "SI"], key="actividad")
    st.selectbox("¿Malos hábitos alimenticios?", ["NO", "SI"], key="habitos")
    c1, c2 = st.columns(2)
    predecir = c1.button("Clasificar", type="primary")
    c2.button("Resetear", on_click=resetear)

if predecir:
    obs = pd.DataFrame({
        "EDAD": [st.session_state["edad"]],
        "SEXO": [st.session_state["sexo"]],
        "ACTIVIDAD_FISICA_BAJA": [st.session_state["actividad"]],
        "MALOS_HABITOS_ALIMENTICIOS": [st.session_state["habitos"]],
    })
    st.write("Datos ingresados:")
    st.dataframe(obs, hide_index=True)

    p_exceso = float(modelo.predict_proba(obs)[0, 1])
    if p_exceso >= 0.5:
        st.markdown("<p style='font-size:32px;color:#c0392b;'>Predicción: CON EXCESO DE PESO</p>",
                    unsafe_allow_html=True)
    else:
        st.markdown("<p style='font-size:32px;color:green;'>Predicción: SIN EXCESO DE PESO</p>",
                    unsafe_allow_html=True)

    col1, col2 = st.columns(2)
    col1.metric("Prob. CON exceso", f"{p_exceso:.1%}")
    col2.metric("Prob. SIN exceso", f"{1 - p_exceso:.1%}")
    st.progress(p_exceso)
    st.caption("Estimación estadística, no es un diagnóstico clínico.")
else:
    st.info("Completa los datos en la barra lateral y presiona **Clasificar**.")